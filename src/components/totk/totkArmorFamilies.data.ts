// e.g. "Armor_003_Head" -> "Armor_001_Head" (tier 3 of the Hylian Hood family, base is tier 1).
// Ids with no upgrade tiers (a single armor piece with no leveled variants) are returned as-is.
export function armorBaseId(id: string): string {
  const numberId = id.replace(/\D/g, "");
  const family = UPGRADE_FAMILIES.find((f) => f.includes(numberId));
  if (!family) return id;
  return id.replace(/\d+/, family[0]);
}
